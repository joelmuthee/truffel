# emoji (variation selectors / ZWJ gender marks stripped) -> icon
MAP = {
    "✨": "sparkles", "✦": "diamond", "✧": "sparkles", "♦": "diamond",
    "✿": "flower", "🌸": "flower", "🌿": "leaf", "⚡": "zap",
    "☎": "phone", "📞": "phone", "✉": "mail", "📍": "pin", "🔬": "microscope",
    "🎓": "cap", "✓": "check", "🏫": "building", "🤝": "heart",
    "🗓": "calendar", "📅": "calendar", "💆": "heart", "🧍": "person",
    "👗": "shirt", "⚖": "scale", "🏃": "activity", "🎯": "target", "🏥": "hospital",
}

EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿]")
ICON_EL = re.compile(r'(class="[^"]*icon[^"]*"[^>]*>)(\s*)([^<]{1,8}?)(\s*)(<)')


def svg(name):
    return ('<svg viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" '
            'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
            + P[name] + "</svg>")


def sub(m):
    key = re.sub("[️‍♀♂]", "", m.group(3)).strip()
    if not EMOJI.search(key):
        return m.group(0)
    if key not in MAP:
        print("  unmapped:", repr(key))
        return m.group(0)
    return m.group(1) + m.group(2) + svg(MAP[key]) + m.group(4) + m.group(5)


def main(files):
    for f in files:
        p = Path(f)
        s = p.read_text(encoding="utf-8")
        new = ICON_EL.sub(sub, s)
        if new != s:
            p.write_text(new, encoding="utf-8", newline="")
            mark = 'width="1em"'
            print(f"{f}: {new.count(mark) - s.count(mark)} icons")


if __name__ == "__main__":
    main(sys.argv[1:] or sorted(glob.glob("*.html") + glob.glob("cosmetic/*.html")))
